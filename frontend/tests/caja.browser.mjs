import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { conectarNavegador } from './browser.mjs'
import { leerEnCaja } from './caja-helpers.mjs'
const n=await conectarNavegador(), {cdp,evaluar,esperar,llenar,click}=n
const frontend=process.env.E2E_FRONTEND_URL
const api=(url,method='get',data)=>evaluar(`(async()=>{const a=(await import('/src/services/api.js')).default;const r=await a.request({url:${JSON.stringify(url)},method:${JSON.stringify(method)},data:${JSON.stringify(data)},validateStatus:()=>true});return {status:r.status,data:r.data}})()`)
try {
  await cdp('Page.enable');await cdp('Runtime.enable');await cdp('Network.enable');await cdp('Network.clearBrowserCookies')
  await cdp('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false})
  await n.navegar(frontend)
  await esperar(`!!document.getElementById('form-login')`,'No mostró login')
  await llenar('form-login',{'Usuario':process.env.E2E_USER,'Contraseña':process.env.E2E_PASSWORD});await click('Iniciar sesión')
  await esperar(`!!document.querySelector('.bienvenida')`,'No abrió Inicio')
  const proveedor=(await api('/catalogos/proveedores')).data.find(p=>p.nombre==='Proveedor Operaciones E2E')
  const producto=(await api('/productos','post',{codigo:'001234',nombre:'Cuaderno Caja E2E',proveedor_id:proveedor._id,precio_costo:'0.47',precio_venta:'1.01',stock_minimo:1,activo:true})).data.datos
  assert.ok(producto._id)
  assert.equal((await api('/ingresos','post',{operacion_id:crypto.randomUUID(),proveedor_id:proveedor._id,motivo:'Stock para caja E2E',items:[{producto_id:producto._id,cantidad:20}]})).status,201)
  await evaluar(`location.hash='ventas'`)
  await esperar(`!!document.querySelector('.pos-caja')&&!document.querySelector('.spinner')`,'No abrió la caja')
  assert.equal(await evaluar(`!!document.querySelector('.fab')`),false)
  assert.equal(await evaluar(`document.activeElement?.getAttribute('aria-label')`),'Buscar o escanear producto')
  await leerEnCaja(n,'5*001234')
  await esperar(`document.querySelector('[data-producto="001234"] input')?.value==='5'`,'No agregó cinco unidades')
  await evaluar(`(()=>{const i=document.querySelector('[aria-label="Buscar o escanear producto"]');for(const t of ['001234','2*001234','001234']){i.value=t;i.dispatchEvent(new Event('input',{bubbles:true}));i.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}))}})()`)
  await esperar(`document.querySelector('[data-producto="001234"] input')?.value==='9'`,'Perdió lecturas rápidas')
  await leerEnCaja(n,'0*001234');await esperar(`document.querySelector('.pos-caja [role="alert"]')?.textContent.includes('cantidad')`,'No rechazó cantidad cero')
  await click('Entendido')
  await leerEnCaja(n,'NO-EXISTE');await esperar(`document.querySelector('.pos-caja [role="alert"]')?.textContent.includes('No existe')`,'No avisó código inexistente')
  await click('Entendido')
  await leerEnCaja(n,'100*001234');await esperar(`document.querySelector('.pos-caja [role="alert"]')?.textContent.includes('solo hay 20')`,'No rechazó exceso de stock')
  await click('Entendido')
  assert.equal(await evaluar(`document.querySelector('[data-producto="001234"] input').value`),'9')
  await evaluar(`[...document.querySelectorAll('.pos-caja button')].find(b=>b.textContent.trim().endsWith('Agregar cliente (NIT)')).click()`)
  await esperar(`!!document.getElementById('buscar-cliente-venta')`,'No abrió NIT')
  await llenar('buscar-cliente-venta',{'NIT o nombre del cliente':'CAJA-001'})
  await click('Agregar por NIT')
  await esperar(`document.querySelector('[role="alert"]')?.textContent.includes('No hay clientes')`,'No avisó NIT inexistente')
  await click('Registrar nuevo cliente')
  await esperar(`!!document.getElementById('form-cliente')`,'No abrió alta de cliente')
  assert.equal(await evaluar(`[...document.querySelectorAll('#form-cliente label')].find(l=>l.querySelector('span')?.textContent==='NIT *').querySelector('input').value`),'CAJA001')
  await llenar('form-cliente',{'Nombre completo *':'Cliente Caja E2E'})
  await click('Guardar cambios','.dialog footer button')
  await esperar(`!document.querySelector('[role="dialog"]')&&document.querySelector('.pos-resumen')?.textContent.includes('Cliente Caja E2E')`,'No asignó el cliente nuevo')
  await mkdir('test-results',{recursive:true})
  await esperar(`getComputedStyle(document.querySelector('.page')).opacity==='1'`,'No terminó animación')
  await writeFile('test-results/caja-escritorio.png',Buffer.from((await cdp('Page.captureScreenshot',{format:'png'})).data,'base64'))
  await click('Guardar (facturar)');await esperar(`!!document.getElementById('form-cobro')`,'No abrió cobro')
  assert.equal(await evaluar(`!!document.querySelector('[aria-label="Código de facturación"]')`),false)
  await llenar('form-cobro',{'Efectivo recibido *':'1.00'});await click('Confirmar cobro')
  await esperar(`document.querySelector('.dialog [role="alert"]')?.textContent.includes('cubrir')`,'No rechazó efectivo insuficiente')
  await llenar('form-cobro',{'Efectivo recibido *':'20.00'});await click('Confirmar cobro')
  await esperar(`!!document.getElementById('form-autorizar')`,'No pidió código al confirmar')
  assert.ok((await evaluar(`document.querySelector('.dialog').textContent`)).includes('Q 10.91'))
  await llenar('form-autorizar',{'Código de facturación (4 dígitos) *':'0000'});await click('Facturar venta')
  await esperar(`document.querySelector('.dialog [role="alert"]')?.textContent.includes('Código de facturación incorrecto')`,'No validó código del usuario')
  await llenar('form-autorizar',{'Código de facturación (4 dígitos) *':'4321'})
  let registrada
  n.interceptar(async solicitud=>{
    if(solicitud.request.method==='POST'&&!registrada) {
      const cuerpo=await cdp('Fetch.getResponseBody',{requestId:solicitud.requestId})
      registrada=JSON.parse(cuerpo.base64Encoded?Buffer.from(cuerpo.body,'base64').toString():cuerpo.body)
      await cdp('Fetch.failRequest',{requestId:solicitud.requestId,errorReason:'ConnectionClosed'})
    }else await cdp('Fetch.continueRequest',{requestId:solicitud.requestId})
  })
  await cdp('Fetch.enable',{patterns:[{urlPattern:'*api/ventas',requestStage:'Response'}]})
  await click('Facturar venta')
  await esperar(`document.querySelector('.dialog')?.textContent.includes('La respuesta no se confirmó')`,'No protegió la respuesta perdida')
  assert.ok(registrada?._id)
  await cdp('Fetch.disable');n.interceptar(null)
  await click('Reintentar facturación','.dialog footer button')
  await esperar(`!!document.querySelector('.comprobante')`,'No recuperó venta con el mismo UUID')
  assert.ok((await evaluar(`document.querySelector('.comprobante').textContent`)).includes('Cliente Caja E2E'))
  assert.equal((await api('/ventas?operacion_id='+registrada.operacion_id)).data.length,1)
  assert.equal((await api('/catalogos/productos?codigo=001234')).data[0].existencia,11)
  assert.equal(registrada.total_centavos,909)
  await click('Cerrar','.dialog footer button')
  await esperar(`document.activeElement?.getAttribute('aria-label')==='Buscar o escanear producto'`,'No devolvió foco al lector')
  await leerEnCaja(n,'001234')
  await esperar(`document.querySelector('[data-producto="001234"] input')?.value==='1'`,'No comenzó la siguiente venta')
  await evaluar(`location.hash='inicio'`);await esperar(`!!document.querySelector('.bienvenida')`,'No cambió vista')
  await evaluar(`location.hash='ventas'`);await esperar(`document.querySelector('[data-producto="001234"] input')?.value==='1'`,'No conservó borrador en memoria')
  await click('Historial y kardex');await esperar(`!!document.querySelector('[data-documento="${registrada._id}"]')`,'No conservó historial')
  await evaluar(`[...document.querySelectorAll('button')].find(b=>b.textContent.trim().endsWith('Volver a la caja')).click()`)
  await cdp('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  assert.equal(await evaluar(`document.documentElement.scrollWidth<=innerWidth`),true)
  await writeFile('test-results/caja-movil.png',Buffer.from((await cdp('Page.captureScreenshot',{format:'png'})).data,'base64'))
  await click('Limpiar detalle');await esperar(`!!document.querySelector('[role="dialog"]')`,'No confirmó limpiar')
  await click('Limpiar detalle','.dialog footer button');await esperar(`!document.querySelector('.pos-detalle')`,'No limpió detalle')
  await evaluar(`document.querySelector('[aria-label="Cerrar sesión"]').click()`)
  await esperar(`!!document.getElementById('form-login')`,'No cerró sesión')
  assert.deepEqual(n.errores,[])
  console.log('OK: caja abierta, N*código y lecturas rápidas, NIT/alta, efectivo/cambio, PIN, respuesta perdida sin duplicar, borrador e historial, foco y móvil')
} finally {await cdp('Emulation.setDeviceMetricsOverride',{width:1365,height:1000,deviceScaleFactor:1,mobile:false});n.cerrar()}
