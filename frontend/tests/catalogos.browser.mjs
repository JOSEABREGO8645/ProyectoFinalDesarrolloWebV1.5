import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { setTimeout as pausa } from 'node:timers/promises'

import { conectarNavegador } from './browser.mjs'

// Requiere un backend aislado con los fixtures de autenticacion.
const frontend = process.env.E2E_FRONTEND_URL || 'http://127.0.0.1:5175'
const usuario = process.env.E2E_USER
const password = process.env.E2E_PASSWORD
assert.ok(usuario && password, 'Configure E2E_USER y E2E_PASSWORD con cuentas de prueba')
const navegador = await conectarNavegador()
const { cdp, evaluar, esperar, click, llenar, buscar, errores } = navegador

try {
  await cdp('Page.enable')
  await cdp('Runtime.enable')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1365, height: 900, deviceScaleFactor: 1, mobile: false })
  await cdp('Network.enable')
  await cdp('Network.clearBrowserCookies')
  await navegador.navegar(`${frontend}/#proveedores`)
  await esperar(`!!document.getElementById('form-login')`, 'No mostro el login')
  await llenar('form-login', { 'Usuario': usuario, 'Contrase\u00f1a': password })
  await click('Iniciar sesi\u00f3n')
  await esperar(`!!document.querySelector('.bienvenida')`, 'No mostro bienvenida')
  await evaluar(`location.hash = 'proveedores'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Proveedores' && !document.querySelector('.spinner')`, 'No cargó Proveedores')
  await click('addAgregar proveedor')
  await esperar(`!!document.getElementById('form-proveedor')`, 'No abrió el formulario')
  await click('Guardar cambios')
  await esperar(`document.querySelector('[role="alert"]')?.textContent.includes('Complete el nombre')`, 'Falta validación local')
  await llenar('form-proveedor', { 'Nombre o razón social *': 'Proveedor E2E', 'NIT': '123456-7', 'Correo': 'proveedor@example.com' })
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t1')?.textContent === 'Proveedor E2E'`, 'No se guardó el proveedor')
  await evaluar(`document.querySelector('[aria-label="Editar proveedor"]').click()`)
  await esperar(`document.querySelector('#form-proveedor input')?.value === 'Proveedor E2E'`, 'No precargó los datos')
  await llenar('form-proveedor', { 'Nombre o razón social *': 'Proveedor editado' })
  await evaluar(`document.querySelector('#form-proveedor input[type="checkbox"]').click()`)
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t1')?.textContent === 'Proveedor editado'`, 'No se editó el proveedor')
  await click('Activos')
  await esperar(`!!document.querySelector('.empty')`, 'El filtro de activos no excluyó al inactivo')
  await click('Inactivos')
  await esperar(`document.querySelectorAll('.li').length === 1`, 'El filtro de inactivos no devolvió el proveedor')
  await buscar('inexistente')
  await esperar(`!!document.querySelector('.empty')`, 'La búsqueda no filtró los resultados')
  await buscar('Proveedor editado')
  await esperar(`document.querySelectorAll('.li').length === 1`, 'La búsqueda no encontró al proveedor')
  await evaluar(`document.querySelector('[aria-label="Eliminar proveedor"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No pidió confirmación')
  await click('Cancelar')
  assert.equal(await evaluar(`document.querySelectorAll('.li').length`), 1)
  await evaluar(`document.querySelector('[aria-label="Eliminar proveedor"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No abrió la segunda confirmación')
  await click('Eliminar')
  await esperar(`!document.querySelector('[role="dialog"]') && !!document.querySelector('.empty')`, 'No eliminó el proveedor')
  console.log('OK: Proveedores: crear, validar, editar, buscar, filtrar, cancelar y eliminar')

  await evaluar(`location.hash = 'clientes'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Clientes' && !document.querySelector('.spinner')`, 'No cargó Clientes')
  await click('addAgregar cliente')
  await esperar(`!!document.getElementById('form-cliente')`, 'No abrió el formulario de cliente')
  await llenar('form-cliente', { 'Nombre completo *': 'Cliente E2E', 'NIT *': '7654-3', 'Teléfono': '2222-1000' })
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t2')?.textContent.includes('76543')`, 'No se guardó o normalizó el NIT')
  await click('addAgregar cliente')
  await esperar(`!!document.getElementById('form-cliente')`, 'No abrió el segundo formulario')
  await llenar('form-cliente', { 'Nombre completo *': 'Duplicado', 'NIT *': '76543' })
  await click('Guardar cambios')
  await esperar(`document.querySelector('[role="alert"]')?.textContent.includes('Ya existe un cliente con ese NIT.')`, 'No rechazó el NIT repetido')
  await click('Cancelar')
  await evaluar(`document.querySelector('[aria-label="Editar cliente"]').click()`)
  await esperar(`document.querySelector('#form-cliente input')?.value === 'Cliente E2E'`, 'No precargó el cliente')
  await llenar('form-cliente', { 'Nombre completo *': 'Cliente editado' })
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t1')?.textContent === 'Cliente editado'`, 'No editó el cliente')
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await pausa(700)
  assert.equal(await evaluar(`document.documentElement.scrollWidth <= innerWidth`), true, 'La página desborda en móvil')
  await mkdir('test-results', { recursive: true })
  await writeFile('test-results/clientes-movil.png', Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await evaluar(`document.querySelector('[aria-label="Editar cliente"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No abrió el diálogo en móvil')
  await pausa(700)
  assert.equal(await evaluar(`(() => { const r = document.querySelector('.scrim').getBoundingClientRect(); return Math.abs(r.width - innerWidth) < 2 && Math.abs(r.height - innerHeight) < 2 })()`), true, 'El fondo del diálogo no cubre la pantalla')
  await writeFile('test-results/cliente-form-movil.png', Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await click('Cancelar')
  await evaluar(`document.querySelector('[aria-label="Eliminar cliente"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No pidió confirmación para el cliente')
  await click('Eliminar')
  await esperar(`!document.querySelector('[role="dialog"]') && !!document.querySelector('.empty')`, 'No eliminó el cliente')
  assert.deepEqual(errores, [], 'Hay excepciones JavaScript en el navegador')
  console.log('OK: Clientes: NIT normalizado, duplicados, edición, eliminación y diseño móvil')

  await evaluar(`location.hash = 'proveedores'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Proveedores' && !document.querySelector('.spinner')`, 'No cargó Proveedores para el catálogo')
  await click('addAgregar proveedor')
  await esperar(`!!document.getElementById('form-proveedor')`, 'No abrió el formulario de proveedor')
  await llenar('form-proveedor', { 'Nombre o razón social *': 'Proveedor del catálogo' })
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t1')?.textContent === 'Proveedor del catálogo'`, 'No creó el proveedor del catálogo')
  await evaluar(`location.hash = 'catalogo'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Catálogo' && !document.querySelector('.spinner') && !document.querySelector('.fab')?.disabled`, 'No cargó el catálogo')
  await click('addAgregar producto')
  await esperar(`!!document.getElementById('form-producto')`, 'No abrió el formulario del producto')
  const proveedorId = await evaluar(`document.querySelector('#form-producto select option:nth-child(2)').value`)
  await llenar('form-producto', { 'Código / código de barras *': 'E2E-001', 'Nombre del producto *': 'Cuaderno E2E', 'Proveedor': proveedorId, 'Categoría': 'Papelería', 'Precio de costo (Q) *': '5.50', 'Precio de venta (Q) *': '10.25' })
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t2')?.textContent.includes('Proveedor del catálogo')`, 'No guardó el producto y su proveedor')
  await click('addAgregar producto')
  await esperar(`!!document.getElementById('form-producto')`, 'No abrió el formulario para el duplicado')
  await llenar('form-producto', { 'Código / código de barras *': 'e2e-001', 'Nombre del producto *': 'Duplicado', 'Precio de costo (Q) *': '1.00', 'Precio de venta (Q) *': '2.00' })
  await click('Guardar cambios')
  await esperar(`document.querySelector('[role="alert"]')?.textContent.includes('Ya existe un producto con ese código.')`, 'No rechazó el código duplicado')
  await click('Cancelar')
  await evaluar(`document.querySelector('[aria-label="Editar producto"]').click()`)
  await esperar(`document.querySelector('#form-producto select')?.value === ${JSON.stringify(proveedorId)}`, 'No precargó el proveedor del producto')
  await llenar('form-producto', { 'Nombre del producto *': 'Cuaderno actualizado', 'Precio de venta (Q) *': '12.50' })
  await click('Guardar cambios')
  await esperar(`!document.querySelector('[role="dialog"]') && document.querySelector('.li .t2')?.textContent.includes('12.50')`, 'No editó el precio del producto')
  await buscar('sincoincidencia')
  await esperar(`!!document.querySelector('.empty')`, 'No buscó en productos')
  await buscar('E2E-001')
  await esperar(`document.querySelectorAll('.li').length === 1`, 'No encontró el producto por código')
  await pausa(700)
  assert.equal(await evaluar(`document.documentElement.scrollWidth <= innerWidth`), true, 'El catálogo desborda en móvil')
  await writeFile('test-results/catalogo-movil.png', Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1365, height: 900, deviceScaleFactor: 1, mobile: false })
  await pausa(700)
  await writeFile('test-results/catalogo-escritorio.png', Buffer.from((await cdp('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await evaluar(`location.hash = 'proveedores'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Proveedores' && document.querySelectorAll('.li').length === 1`, 'No volvió a Proveedores')
  await evaluar(`document.querySelector('[aria-label="Eliminar proveedor"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No pidió confirmación del proveedor en uso')
  await click('Eliminar')
  await esperar(`document.querySelector('.toast')?.textContent.includes('Este proveedor tiene productos')`, 'No bloqueó la eliminación del proveedor en uso')
  await evaluar(`location.hash = 'catalogo'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Catálogo' && document.querySelectorAll('.li').length === 1`, 'No volvió al catálogo')
  await evaluar(`document.querySelector('[aria-label="Eliminar producto"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No confirmó la eliminación del producto')
  await click('Eliminar')
  await esperar(`!document.querySelector('[role="dialog"]') && !!document.querySelector('.empty')`, 'No eliminó el producto')
  await evaluar(`location.hash = 'proveedores'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Proveedores' && document.querySelectorAll('.li').length === 1`, 'No volvió al proveedor sin uso')
  await evaluar(`document.querySelector('[aria-label="Eliminar proveedor"]').click()`)
  await esperar(`!!document.querySelector('[role="dialog"]')`, 'No confirmó el proveedor sin uso')
  await click('Eliminar')
  await esperar(`!document.querySelector('[role="dialog"]') && !!document.querySelector('.empty')`, 'No eliminó el proveedor sin uso')
  assert.deepEqual(errores, [], 'Hay excepciones JavaScript en el catálogo')
  console.log('OK: Productos: proveedor dinámico, código único, precios, edición, búsqueda, integridad y diseño móvil/escritorio')
  await evaluar(`location.hash = 'clientes'`)
  await esperar(`document.querySelector('h1')?.textContent === 'Clientes' && !document.querySelector('.spinner')`, 'No cambió de módulo antes de simular el error')
  await cdp('Fetch.enable', { patterns: [{ urlPattern: '*api/proveedores/buscar*', requestStage: 'Request' }] })
  await evaluar(`location.hash = 'proveedores'`)
  await esperar(`document.querySelector('[role="alert"]')?.textContent.includes('No hay conexión con el servidor')`, 'No mostró el error de conexión')
  assert.equal(await evaluar(`!!document.querySelector('.empty')`), false, 'Un error de conexión se mostró como catálogo vacío')
  await cdp('Fetch.disable')
  await click('Reintentar')
  await esperar(`!document.querySelector('[role="alert"]') && !!document.querySelector('.empty')`, 'No recuperó el catálogo al reintentar')
  console.log('OK: Error de red visible y recuperación con Reintentar')
} finally {
  navegador.cerrar()
}
